package Typesofexception;

public class checkedandunchecked {

	
	/*
	 
	 
	 Exception 
	 there are two types
	 1) checked
	 2) unchecked
	 
	 1) Checked exceptions-
       * Compiler known exception
	   * these kind of exception should be handle immediately 
	   * These inherit directly Exception directly
	     ex - thread class, file not found exception , interrupted exception
	 
	 2) Unchecked exceptions
	   * Compiler unknown exception
	   * can not handle immediately
	   * these inherit runtime exception class
	     EX - arithmetic, indexoutofboundary, null pointer
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 */
	
	
	
	
	
	
	
	
	
	
	
	
	
	
}
