	/*
	 
	 Custom exception
	     - Based on the project, it is sometimes necessary to create our own exception and those
	       exceptions which user or programmer creates are called as custom exceptions
	       
	 Rules for creating custom exception
	 
	 1) Create a Class with exception name
	 2) The exception class which we created should either inherit the exception class
	     or inherit the runtime exception class
	 3) Create an object of exception class and invoke/throw the object of exception class
	 4) Handle it using with try and catch block
	 
	  throw 
	  
	  - throw is keyword used to invoke object of exception class
	  - throw is generally used with custom exception
	  
	  syntax
	        - throw objectofexceptiontype; // throw new Exceptionname();         
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 
	 */
	
	
	
